import { FRONT_ROOT, BACK_ROOT, 백엔드있음, 주석제거 } from './_roots.mjs';
import { readFileSync } from 'fs';

// 가이드가 말하는 것과 실제 화면이 같은지 본다.
//
// [왜 필요한가]
//   가이드는 코드와 따로 산다. 화면을 옮기거나 이름을 바꿔도 가이드는 그대로 남고,
//   틀린 안내는 없는 것보다 나쁘다 — 사장님은 없는 메뉴를 찾다가 문의를 넣는다.
//   2026-09-07 점검에서 실제로 이런 것들이 나왔다:
//     · 「설정관리 › 배송비설정」 — 사이드바에 그런 메뉴가 없다(기본설정 화면 안의 탭이다)
//     · 비밀번호 초기화를 결제사(office@forspay.com)로 문의하라고 안내
//     · '도메인을 설정합니다' — 실제로는 잠겨 있다(level 50 전용)
//     · '파비콘·테마색상을 바꿀 수 있다' — 무료몰에는 그 칸이 없다
//   여기서 그 종류의 어긋남을 다시 못 들어오게 막는다. 문구 전체가 아니라
//   '틀리면 사장님이 헛걸음하는 낱말'만 본다.

let pass = 0, fail = 0;
const t = (name, cond, 곁들임) => {
    if (cond) { pass++; console.log('  ok  ' + name); }
    else { fail++; console.log('  FAIL ' + name + (곁들임 ? '\n        ' + 곁들임 : '')); }
};
const 읽기 = (p) => readFileSync(FRONT_ROOT + p, 'utf8');

const 가이드 = 읽기('src/components/manager/guideContent.js');
// 주석에도 같은 낱말이 나온다(왜 고쳤는지 적어 두었다). 사장님이 읽는 본문만 본다.
const 본문 = 주석제거(가이드);
const 설정화면 = 읽기('src/pages/manager/settings/default/[brand_id].js');
const 메뉴 = 읽기('src/layouts/manager/nav/config-navigation.js');

// ── 배송비설정: 사이드바 메뉴가 아니라 기본설정 화면의 탭 ────────────────
t('배송비설정 탭이 기본설정 화면에 있다', /label: '배송비설정'/.test(설정화면));
t('사이드바에는 배송비설정 메뉴가 없다', !/title: '배송비설정'/.test(메뉴),
    '메뉴로 올라왔다면 가이드 문구를 되돌려야 한다');
t('가이드가 배송비설정을 기본설정 안에서 찾게 한다',
    !/설정관리 › 배송비설정/.test(본문),
    "'설정관리 › 배송비설정' 은 없는 메뉴다 — '설정관리 › 기본설정 › 「배송비설정」 탭' 으로 적을 것");

// ── 문의처: 쇼핑몰 문의와 결제 문의는 회사가 다르다 ──────────────────────
const 레이아웃 = 읽기('src/components/main-site/MainSiteLayout.js');
const 쇼핑몰메일 = 레이아웃.match(/SHOP_INQUIRY_EMAIL = '([^']+)'/)?.[1];
const 결제메일 = 레이아웃.match(/PAY_INQUIRY_EMAIL = '([^']+)'/)?.[1];
t('푸터의 두 문의처를 읽었다', !!쇼핑몰메일 && !!결제메일, `${쇼핑몰메일} / ${결제메일}`);
t('계정 문의는 쇼핑몰 문의처로 보낸다', 본문.includes(쇼핑몰메일 ?? '없음'),
    `비밀번호·계정은 쇼핑몰 쪽 일이다 — ${쇼핑몰메일} 로 적을 것`);
t('가이드가 계정 문의를 결제사로 보내지 않는다', !본문.includes(결제메일 ?? '없음'),
    `${결제메일} 은 결제(㈜포스페이) 문의처다`);

// ── 도메인 칸은 잠겨 있다 ────────────────────────────────────────────────
t('도메인 칸이 본사 전용으로 잠겨 있다', /label='도메인'[\s\S]{0,200}disabled=\{user\?\.level < 50\}/.test(설정화면));
t('가이드가 도메인을 잠겨 있다고 적는다', /도메인 칸은 보이지만 잠겨 있습니다/.test(본문),
    "'도메인을 설정합니다' 로 적으면 왜 안 고쳐지는지 몰라 문의가 온다");

// ── 무료몰(SHOPGO 산하)에 없는 칸 ────────────────────────────────────────
// 다크 로고·파비콘·테마색상은 isShopgoMerchant 로 감춘다. '바꿀 수 있다'고 적으면 안 된다.
t('무료몰에는 파비콘·테마색상 칸이 없다', /!isShopgoMerchant\(item\) && \(/.test(설정화면));
const 무엇을바꾸나 = 본문.slice(본문.indexOf("id: 'overview'"));
t('「무엇을 바꿀 수 있나요」가 무료몰 예외를 밝힌다',
    /무료몰은 다크 로고·파비콘·테마색상 칸이 없습니다/.test(무엇을바꾸나),
    '없는 칸을 있다고 적으면 사장님이 찾다가 문의한다');

// ── 카테고리 메뉴 이름 ───────────────────────────────────────────────────
// 사이드바 이름은 '<카테고리 그룹 이름> 관리' 로 만들어지고, 단일 트리로 바뀐 브랜드에서는
// 백엔드가 그룹 이름을 '카테고리' 로 내려준다 → 「카테고리 관리」.
t('메뉴 이름은 그룹 이름 + 관리 로 만든다', /category_group_name'\] \+ ' 관리'/.test(메뉴));
if (백엔드있음) {
    const shop = readFileSync(BACK_ROOT + 'controllers/shop.controller.js', 'utf8');
    t('단일 트리 브랜드의 그룹 이름이 「카테고리」다', /category_group_name: '카테고리'/.test(shop));
    t('가이드가 「상품관리 › 카테고리 관리」로 안내한다', /상품관리 › 카테고리 관리/.test(본문));

    // ── 손님이 취소요청을 낼 수 있는 상태 ────────────────────────────────
    const trx = readFileSync(BACK_ROOT + 'controllers/transaction.controller.js', 'utf8');
    const 가능상태 = trx.match(/CANCELABLE_STATUS = \[([^\]]+)\]/)?.[1]?.replace(/\s/g, '');
    t('취소 가능 상태는 결제완료(5)·입고(10) 뿐이다', 가능상태 === '5,10', `실제: [${가능상태}]`);
    t('가이드도 결제완료·입고까지라고 적는다',
        (본문.match(/「결제완료」와 「입고」까지/g) || []).length >= 2,
        '결제대기(0)는 취소요청이 막힌다 — 그 이유까지 함께 적혀 있어야 한다');
} else {
    console.log('  --  백엔드 폴더가 없어 3건은 건너뜀');
}

// ── 팝업 추가 버튼 이름 ──────────────────────────────────────────────────
const 팝업목록 = 읽기('src/pages/manager/designs/popup/list.js');
const 팝업버튼 = 팝업목록.match(/add_button_text=\{'([^']+)'\}/)?.[1];
t('가이드가 팝업 추가 버튼을 실제 이름으로 부른다', 팝업버튼 ? 본문.includes(`「${팝업버튼}」`) : false,
    `실제 버튼: 「${팝업버튼}」`);

// ── 대시보드 매출 조회는 외부 사이트다 ───────────────────────────────────
const 대시보드 = 읽기('src/views/manager/dashboards/demo-2.js');
const oms = /oms\.forspay\.net/.test(대시보드);
t('매출 조회는 포스페이 OMS 로 나간다', oms);
t('가이드가 외부 사이트·별도 로그인임을 알린다', /포스페이 OMS 사이트가 새 탭으로/.test(본문),
    '우리 화면인 줄 알고 로그인 화면을 보면 고장난 줄 안다');

console.log(`\n통과 ${pass} / 실패 ${fail}`);
process.exit(fail ? 1 : 0);
