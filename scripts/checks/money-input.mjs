import { FRONT_ROOT } from './_roots.mjs';
import { readdirSync, readFileSync, statSync } from 'fs';

// 관리자 금액칸이 쉼표 없이 맨숫자로 떠 있지 않은지 본다.
//
// 왜 필요한가:
//   <input type="number"> 는 쉼표를 못 받는다 — 넣으면 값이 통째로 무효가 된다.
//   그래서 금액칸이 전부 '15000' 처럼 붙어 있었고, 0 을 세다 자리를 틀리면 그대로 저장됐다.
//   배송비 1,500원과 15,000원은 눈으로는 붙어 보인다.
//
//   상품의 판매가·정가는 진작부터 type="text" + toLocaleString 으로 쉼표를 넣고 있었다.
//   방법이 없어서가 아니라 그 방식이 다른 칸에 안 퍼져 있었을 뿐이다.
//
// 판정: 금액을 뜻하는 라벨이 붙은 칸에 type="number" 가 남아 있으면 잡는다.
//       비율(수수료율·적립률)은 대상이 아니다 — 쉼표를 넣을 값이 아니다.

let pass = 0, fail = 0;
const t = (name, cond) => { if (cond) { pass++; console.log('  ok  ' + name); } else { fail++; console.log('  FAIL ' + name); } };

// ── 변환 규칙을 실제로 돌려 본다 ──────────────────────────────────────────
const 소스 = readFileSync(FRONT_ROOT + 'src/utils/money-input.js', 'utf8')
    .replace(/\bexport const /g, 'const ');
const { 금액표시, 금액값, 커서자리 } = new Function(소스 + 'return { 금액표시, 금액값, 커서자리 };')();

t('천 단위로 끊는다', 금액표시(15000) === '15,000');
t('문자열로 들어와도 끊는다', 금액표시('15000') === '15,000');
t('이미 쉼표가 있어도 두 번 안 끊는다', 금액표시('15,000') === '15,000');
t('0 은 0 으로 보인다', 금액표시(0) === '0');
// 비우면 0 이 아니라 빈 칸이어야 한다 — 0 으로 되돌리면 지우는 순간 0 이 따라붙어 못 지운다.
t('빈 값은 빈 칸', 금액표시('') === '' && 금액표시(null) === '' && 금액표시(undefined) === '');
t('쉼표를 떼어 담는다', 금액값('15,000') === '15000');
t('글자가 섞여도 숫자만 남는다', 금액값('1a5,0원00') === '15000');
t('앞자리 0 을 떨군다', 금액값('05') === '5');       // '0' 에서 5 를 치면 '05' 가 되던 것
t('음수는 살린다', 금액값('-3,000') === '-3000');    // 포인트 차감
t('다 지우면 빈 값', 금액값('') === '' && 금액값('원') === '');
t('숫자가 아닌 값이 들어와도 안 죽는다', 금액표시('abc') === '');

// ── 커서가 제자리에 남는가 ────────────────────────────────────────────────
// 쉼표가 끼면 글자 수가 저 혼자 늘고 준다. 그대로 두면 칸 중간을 고칠 때마다 커서가
// 끝으로 튀어서, 12,345 의 3 을 고치려던 사람이 뒤에 숫자를 붙이게 된다.
// 세는 것은 '숫자를 몇 개 지나왔나' 이므로, 쉼표가 하나 생기든 사라지든 결과가 같아야 한다.
const 커서옮김 = (친값, 커서) => 커서자리(친값, 커서, 금액표시(금액값(친값)));

// 1234 뒤에 5 → 12,345. 커서는 여전히 5 개 숫자 뒤(끝).
t('쉼표가 새로 생겨도 같은 숫자 옆', 커서옮김('12345', 5) === 6);
// 12,345 에서 3 뒤(인덱스 4)를 고칠 때 — 쉼표를 건너뛰고 세 번째 숫자 뒤에 놓인다.
t('중간을 고쳐도 제자리', 커서옮김('12,345', 4) === 4);
// 맨 앞 숫자 하나를 지워 1,234 가 되면 쉼표가 한 칸 앞으로 온다.
t('쉼표가 사라져도 같은 숫자 옆', 커서옮김('2,345', 1) === 1);
t('맨 앞이면 맨 앞', 커서옮김('12,345', 0) === 0);
t('끝이면 끝', 커서옮김('12,345', 6) === 6);
// 음수 칸에서 빼기표 뒤에 커서를 두면 그 자리에 남아야 한다(앞으로 밀리면 부호를 지우게 된다).
t('빼기표 뒤에 남는다', 커서옮김('-3,000', 1) === 1);

// ── 화면에 맨숫자 칸이 남아 있는가 ────────────────────────────────────────
const 훑기 = (d, out = []) => {
    for (const f of readdirSync(d)) {
        const p = d + '/' + f;
        if (statSync(p).isDirectory()) 훑기(p, out);
        else if (f.endsWith('.js')) out.push(p);
    }
    return out;
};
const 돈말 = /(가격|금액|배송비|비용|요금|판매가|원가|공급가|적립 포인트|부여할포인트|수수료)/;
const 비율 = /(비율|률|율\()/;

const 걸린것 = [];
for (const p of [...훑기(FRONT_ROOT + 'src/pages/manager'), ...훑기(FRONT_ROOT + 'src/views/manager')]) {
    const 줄 = readFileSync(p, 'utf8').split('\n');
    줄.forEach((l, i) => {
        if (!/type\s*=\s*[{']?["']?number/.test(l)) return;
        // 라벨은 이 줄 앞뒤에서 찾는다(칸에 따라 type 이 label 위에도 아래에도 온다).
        const 주변 = 줄.slice(Math.max(0, i - 4), i + 5).join(' ');
        const m = 주변.match(/label\s*=\s*['"`]([^'"`]+)['"`]/);
        if (m && 돈말.test(m[1]) && !비율.test(m[1])) {
            걸린것.push(`${p.replace(FRONT_ROOT, '')}:${i + 1}  ${m[1]}`);
        }
    });
}
if (걸린것.length) for (const x of 걸린것) console.log('        ' + x);
t('쉼표 없는 금액칸이 남아 있지 않다', 걸린것.length === 0);

// 상품 판매가·정가는 예전부터 쉼표를 넣고 있었다 — 되돌아가지 않았는지 같이 본다.
const 상품 = readFileSync(FRONT_ROOT + 'src/pages/manager/products/[edit_category]/[id].js', 'utf8');
t('판매가는 여전히 쉼표를 쓴다', /toLocaleString\('ko-KR'\)/.test(상품));

console.log(`\n통과 ${pass} / 실패 ${fail}`);
process.exit(fail ? 1 : 0);
