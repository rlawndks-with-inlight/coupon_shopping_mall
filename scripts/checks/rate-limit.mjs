import { BACK_ROOT, 백엔드있음, 주석제거 } from './_roots.mjs';
import { readFileSync } from 'fs';

// 사람이 몰렸을 때 몰이 통째로 안 보이는 일을 막는다 (2026-08-31).
//
// [무엇이 있었나 — 실측]
// 백엔드는 한 IP 가 분당 300건을 넘기면 429 를 준다(손님 보호용, 그 자체는 옳다).
// 그런데 프론트는 페이지를 그릴 때마다 `_app.js` 의 getInitialProps 에서 `/api/domain` 을 부른다.
// 그 호출은 손님 한 명이 아니라 **모든 손님의 페이지 요청이 프론트 서버 한 IP 로 모인 것**이다.
//   → 분당 300건 = **몰 전체가 초당 5페이지**에서 막힌다.
// 게다가 프론트는 429 응답의 `data:false` 를 보고 '등록되지 않은 주소' 로 단정해 **404** 를 냈다.
//   → 부하시험에서 동시 20명이면 멀쩡한 몰의 거의 모든 요청이 404 였다.
//
// 두 겹으로 고쳤다. 하나만 고치면 다른 쪽이 흔들릴 때 같은 일이 난다.
//   ① 백엔드: 프론트 서버 IP 는 속도제한에서 뺀다(손님별 보호는 그대로).
//   ② 프론트: 응답이 200 이 아니면 '없는 몰' 로 단정하지 않는다.

let pass = 0, fail = 0;
const t = (name, cond, 곁들임) => {
    if (cond) { pass++; console.log('  ok  ' + name); }
    else { fail++; console.log('  FAIL ' + name + (곁들임 ? '\n        ' + 곁들임 : '')); }
};
const 읽기 = (p) => readFileSync(p, 'utf8').split(String.fromCharCode(13)).join('');

// ── 프론트: 429·5xx 를 '없는 몰' 로 읽지 않는다 ──────────────────────────
const 앱 = 읽기('src/pages/_app.js');
t('응답이 200 이 아니면 없는 몰로 단정하지 않는다', /if \(!res\.ok\) \{/.test(앱),
    '429 의 본문도 data:false 라, 그것만 보면 멀쩡한 몰이 404 가 된다');
// ⚠ is_brand_not_found 는 두 곳에 있다 — 위쪽(96줄 부근)은 '안내 화면을 그리는' 자리고,
//   뒤쪽이 '404 로 판정하는' 자리다. 앞의 것과 비교하면 늘 빨간불이 된다(내가 한 번 밟았다).
t('그 검사가 404 판정보다 앞이다',
    앱.indexOf('if (!res.ok) {') < 앱.indexOf('is_brand_not_found: true'),
    '뒤에 두면 이미 404 로 나간 뒤다');
t('브랜드없음 판정 자체는 남아 있다', /is_brand_not_found: true/.test(앱),
    '진짜 없는 주소는 계속 404 여야 한다 — 죽은 주소가 색인되면 안 된다');

// ── 백엔드: 프론트 서버는 속도제한에서 뺀다 ─────────────────────────────
if (!백엔드있음) {
    console.log('  건너뜀 — 백엔드 저장소가 없다');
} else {
    const 색인 = 주석제거(읽기(BACK_ROOT + 'index.js'));
    t('속도제한이 있다', /rateLimit\(\{/.test(색인),
        '없으면 한 사람이 API 를 마음껏 두드릴 수 있다');
    t('손님별로 센다', /trust proxy/.test(색인),
        "이게 없으면 모두가 nginx IP 하나로 묶여 전체가 분당 300건이 된다");
    t('내부 서버는 제한에서 뺀다', /skip: \(req\) => 제한제외IP\.includes\(req\.ip\)/.test(색인),
        '프론트 SSR 호출이 손님 몫을 다 써 버린다');
    t('제외 주소를 환경변수로 바꿀 수 있다', /RATE_LIMIT_SKIP_IPS/.test(색인),
        '서버를 늘리거나 IP 가 바뀌면 재배포 없이 고칠 수 있어야 한다');
    t('프론트 서버 주소가 기본값에 있다', /13\.125\.9\.31/.test(색인));
    t('손님 상한은 그대로 둔다', /max: 300/.test(색인),
        '내부만 빼는 것이지 보호를 없애는 게 아니다');
}

console.log(`\n통과 ${pass} / 실패 ${fail}`);
process.exit(fail ? 1 : 0);
