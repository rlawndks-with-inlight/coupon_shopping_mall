// 말도 안 되는 값이 저장되지 않게 한다 — 상품 밖의 저장 화면들 (2026-08-28).
//
// [어떻게 찾았나] 운영 API 에 이상한 값을 실제로 넣어 보았다. 아래가 전부 '성공' 으로 통과했다.
//   · 포인트 999,999,999,999 / 1.5 / 0 / 'abc' — `points.point` 는 **double** 이라 DB 도 안 막는다.
//     결제는 `SELECT SUM(point)` 로 잔액을 보므로 **넣은 값이 곧 쓸 수 있는 돈**이다.
//     실제로 시험 계정 잔액이 1조 원이 됐다(행은 즉시 삭제).
//   · 후기 별점 -5 — tinyint 라 999·문자만 DB 가 막았고, 그때도 화면엔 '성공' 이 떴다.
//   · 글 제목 빈 값 · 카테고리 이름 빈 값
//
// [원칙] 뜻이 성립하지 않는 값은 짐작해서 고치지 말고 되돌려 보낸다.
// ⚠ 서버 문구는 사전에서 글자 그대로 찾으므로 조립(템플릿 리터럴)하면 안 된다.

let pass = 0, fail = 0;
const t = (name, cond, 곁들임) => {
    if (cond) { pass++; console.log('  ok  ' + name); }
    else { fail++; console.log('  FAIL ' + name + (곁들임 ? '\n        ' + 곁들임 : '')); }
};

if (!백엔드있음) {
    console.log('  건너뜀 — 백엔드 저장소가 없다(서버에는 프론트만 배포된다)');
    console.log('\n통과 0 / 실패 0');
    process.exit(0);
}
