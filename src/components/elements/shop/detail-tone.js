// 상품상세 '가격 아래 안내 묶음' 의 공용 톤.
//
// 배송비 · 배송 안내 · 혜택 세 줄은 화면에서 한 표처럼 붙어 있다.
// 그런데 각자 자기 값을 들고 있어서 계속 어긋났다(2026-08-28 가맹점 지적 두 번):
//     · 배송비 #888 / 배송 안내 #333 — 글자색이 달라 다른 것처럼 보였다
//     · 배송 안내가 라벨 칸을 안 지켜 혜택과 세로줄이 안 맞았다
// 값을 여기 한 곳에만 두고 셋이 가져다 쓴다. 한쪽만 고쳐지는 일이 없어진다.
//
// 배치는 이렇게 된다:
//
//     |<- 라벨폭 52 ->|<-간격10->|
//     배송비           5,000원 · 30,000원 이상 무료배송
//                      제주추가 10,000원, 그 외 도서지역 추가 20,000원
//     혜택             2026년 07월 카드사 무이자 할부 안내  >
//
// 배송 안내는 라벨이 없으므로 라벨폭+간격(62)만큼 들여써서 내용 칸에 맞춘다.
export const 상세톤 = {
    labelColor: '#888',   // 왼쪽 라벨(배송비·혜택)
    textColor: '#333',    // 오른쪽 내용
    fontSize: 13,
    labelWidth: 52,       // 라벨 칸 고정폭 — 이게 같아야 세로줄이 맞는다
    gap: 10,              // 라벨과 내용 사이
    rowGap: 6,            // 줄 사이
    lineHeight: 1.7,
};

// 라벨이 없는 줄(배송 안내)이 내용 칸에 맞으려면 이만큼 들여쓴다.
export const 내용들여쓰기 = (t = 상세톤) => t.labelWidth + t.gap;
