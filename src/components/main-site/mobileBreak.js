import { Fragment } from 'react';
import { Box } from '@mui/material';

// 문구의 '|' 위치에서 모바일만 줄을 바꾼다. PC(md+)에서는 원문 그대로 한 줄로 이어진다.
//
// 왜 브라우저에 맡기지 않는가
//   ① 끊는 자리가 기기마다 달라진다. 같은 문장이 360px 폭에선 보기 좋게 끊기고
//      390px 폭에선 끝 어절 하나만 다음 줄로 떨어진다.
//        미리보기를 통해 실제 디자인과 화면 구성을 확인하실
//        수 있습니다                                  ← 폭이 한 어절만큼 넓어서 생긴 일
//   ② text-wrap: balance 는 줄 길이만 맞출 뿐 '어디서 끊는 게 말이 되는지'는 모른다.
//      balance 가 고른 자리는 '실제 디자인과 / 화면 구성을' 로, 한 덩어리인 목적어를 쪼갠다.
//      사람이 고르면 '… 화면 구성을 / 확인하실 수 있습니다' 로 목적어와 서술어 사이에서 끊는다.
//   ③ <br/> 이 낀 블록에서는 balance 가 앞 문장에만 걸리는 것도 확인했다.
//
// 쓰는 법
//   사전 문구에 '|' 를 넣는다. 앞 조각 끝의 공백은 '|' 앞에 둔다 —
//   PC 에서 한 줄로 이어질 때 그 공백이 어절 사이 띄어쓰기가 된다.
//     '사업자 누구나 가장 빠르고 간편하게 |나만의 쇼핑몰을 운영할 수 있습니다'
//   띄어쓰기가 없는 일본어·중국어는 '|' 가 유일한 줄바꿈 지점이 된다.
//   '|' 가 없는 문구는 그냥 통째로 렌더된다(짧아서 한 줄에 들어가는 문구는 넣지 않아도 된다).
export const MobileBreakText = ({ text }) =>
  String(text ?? '')
    .split('|')
    .map((part, i) => (
      <Fragment key={i}>
        {i > 0 && <Box component="br" sx={{ display: { xs: 'block', md: 'none' } }} />}
        {part}
      </Fragment>
    ));

export default MobileBreakText;
