//   shots가 없는 항목은 스크린샷이 추가되면 캡션 없이 자동 표시됨.

// ── 프레임 계열 ───────────────────────────────────────────────────────────
// 같은 SHOPGO 몰이라도 프레임에 따라 '메인 화면을 꾸미는 방법'이 아예 다르다.
// 가이드는 지금까지 계열 구분 없이 모든 항목을 다 보여줬다. 그래서
//  · 프레임3·4 가맹점은 「디자인관리 › 메인페이지관리」 버튼을 눌러도 쇼핑몰용 경로로 가고
//    (같은 이름의 메뉴지만 경로가 다르다 = /designs/blog-main),
//  · 프레임5·6 가맹점은 아예 없는 메뉴를 찾아 헤맸다(이 계열엔 섹션 배치 UI 자체가 없다).
// 각 항목에 groups 를 달아 자기 프레임에 해당하는 것만 보이게 한다.
//   shop    프레임1·2     — 디자인관리 › 메인페이지관리 (섹션 배치)
//   column  프레임3·4     — 디자인관리 › 메인페이지관리 (같은 편집기, 경로만 다름 = blog-main)
//   landing 프레임5·6     — 섹션 배치 없음. 대표 상품 + 홈 문구로 홈이 만들어진다.
// groups 가 없는 항목은 모든 계열에 해당한다.
export const FRAME_GROUP_LABEL = {
  shop: '프레임1·2',
  column: '프레임3·4',
  landing: '프레임5·6',
};

// 브랜드 → 계열. 판정 기준은 config-navigation 의 SECTION_BUILDER_* 와 같은 규칙이다
// (블로그 4~9 만 섹션 빌더가 없다). 프레임이 아직 안 정해진 브랜드는 null → 전부 표시.
export const frameGroupOf = (dns) => {
  if (Number(dns?.shop_demo_num) > 0) return 'shop';
  const blog = Number(dns?.blog_demo_num);
  if (blog >= 4) return 'landing';
  if (blog > 0) return 'column';
  return null;
};

// 계열별 이동 경로 — routeByGroup 이 있으면 그 값이 route 보다 우선한다.
export const guideRouteOf = (section, group) =>
  (group && section?.routeByGroup?.[group]) || section?.route || null;

// 브랜드 → 화면에 보이는 프레임 번호(1~6).
// 저장값과 보이는 번호가 다르다 — frameList.js 의 key(저장값) / no(보이는 번호) 대응표를 여기 옮겨 적는다
// (guideContent 는 import 를 쓸 수 없다. PDF 추출기가 이 파일을 통째로 평가하기 때문 → 어긋남은 검사로 막는다).
// 판매 중단된 틀(shop:4, blog:5)을 쓰는 브랜드는 번호가 없다 → null. 이때는 계열 안내까지만 좁혀 준다.
const FRAME_NO = { 'shop:1': 1, 'shop:2': 2, 'blog:1': 3, 'blog:2': 4, 'blog:4': 5, 'blog:9': 6 };
export const frameNoOf = (dns) => {
  const shop = Number(dns?.shop_demo_num) || 0;
  const blog = Number(dns?.blog_demo_num) || 0;
  return FRAME_NO[shop > 0 ? `shop:${shop}` : `blog:${blog}`] ?? null;
};

// 항목뿐 아니라 항목 '안의 칸'도 계열·프레임을 탄다.
// 프레임1 가맹점에게 「프레임2 미리보기는 이렇게」는 읽을 필요가 없는 줄이고, 그런 줄이 섞여 있으면
// 어느 것이 내 이야기인지 매번 골라 읽어야 한다.
// 계열·프레임을 모르는 화면(신청 전 랜딩 /manual, PDF)에서는 전부 보여준다 — 거기서는 비교표가 된다.
export const guideFieldsOf = (section, group, frameNo) =>
  (section?.fields ?? []).filter((f) =>
    (!f.groups || !group || f.groups.includes(group)) &&
    (!f.frames || !frameNo || f.frames.includes(frameNo)));

// 프레임을 알면 제목도 좁힌다(「디자인관리 — 프레임1·2」 → 「디자인관리 — 프레임1」).
export const guideTitleOf = (section, frameNo) =>
  (frameNo && section?.titleByFrame?.[frameNo]) || section?.title;

