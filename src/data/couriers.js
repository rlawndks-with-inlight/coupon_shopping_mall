// 택배사 목록.
//
// 주문관리(택배사/송장번호)와 설정관리(기본 택배사)가 같은 목록을 써야 한다.
// 예전에는 주문관리 파일 안에만 있어서, 설정에서 고른 값이 주문 화면 목록에 없으면
// 드롭다운이 빈 채로 뜨는(=고른 적 없는 것처럼 보이는) 어긋남이 생길 수 있었다.
export const COURIER_LIST = [
    'CJ대한통운', '우체국택배', '한진택배', '롯데택배', '로젠택배',
    '경동택배', 'GS Postbox', 'CU 편의점택배', '대신택배', '일양로지스', '기타',
];

// 이 브랜드의 기본 택배사. 설정한 적이 없으면 빈 문자열('택배사 선택').
// 목록에 없는 값이 저장돼 있으면(목록이 바뀐 경우) 없는 것으로 본다 —
// 드롭다운에 없는 값을 넣으면 MUI Select 가 빈 칸으로 그린다.
export const 기본택배사 = (dns) => {
    const v = String(dns?.setting_obj?.default_courier ?? '');
    return COURIER_LIST.includes(v) ? v : '';
};
