// 포인트 규칙 — 한 곳에서만 정한다.
//
// 왜 필요한가:
//   같은 규칙이 세 군데에 서로 다른 완성도로 흩어져 있었다.
//     · 주문 요약 위젯(CheckoutSummary) — 보유·최대설정·주문금액만 봤다
//     · 주문서 제출 검사(OrderSheet)   — 적립형 최소 보유까지 봤다
//     · 백엔드 결제(pay.controller)     — 잔액만 봤다
//   그래서 화면이 '쓸 수 있다'고 한 값을 제출에서 막거나, 반대로 화면이 막은 값을
//   서버는 통과시키는 어긋남이 생겼다. 규칙을 여기 한 곳에 두고 셋이 같이 부른다.
//   (백엔드에도 같은 규칙을 둔다 — 화면 계산은 서버 검증을 대신할 수 없다)
//
// 설정 값(설정관리 › 포인트설정):
//   use_point_min_price 주문금액이 이 값 이상이어야 쓸 수 있다   (0 = 조건 없음)
//   point_use_min       보유 포인트가 이 값 이상이어야 쓸 수 있다 (0 = 조건 없음)
//   max_use_point       한 주문에 쓸 수 있는 최대 포인트
//   point_rate          적립비율(%)
//
// ── 왜 '즉시사용형 / 적립형' 택일을 없앴나 ────────────────────────────────
//   예전에는 point_policy_type 으로 둘 중 하나만 골랐고, 고른 쪽의 조건만 걸렸다.
//   즉시사용형을 고르면 '최소 보유 포인트' 칸은 화면에 남아 있는데 아무 효과가 없었다 —
//   가맹점이 값을 채워 넣고도 안 걸리는 죽은 칸이다.
//
//   국내 쇼핑몰(카페24·메이크샵 등)은 이 둘을 택일로 두지 않는다. '얼마 이상 주문할 때'와
//   '얼마 이상 모였을 때'는 서로 다른 것을 막는 별개의 장치이고, 보통 둘 다 건다.
//     · 최소 주문금액 — 소액 주문에 포인트를 몰아 쓰는 것을 막는다(배송비만 남기는 주문)
//     · 최소 보유     — 10P·20P 를 매번 소진하며 장부만 늘리는 것을 막는다
//   택일이면 둘 중 하나는 반드시 포기해야 하는데, 포기할 이유가 없다.
//
//   그래서 둘 다 조건으로 건다. 각 값이 0 이면 그 조건은 없는 것으로 본다 — 아무것도
//   설정하지 않은 가맹점은 예전과 똑같이 아무 조건 없이 쓸 수 있다.
//   (point_policy_type 은 더 이상 읽지 않는다)

const 수 = (v) => {
    const n = Number(String(v ?? '').replace(/,/g, ''));
    return Number.isFinite(n) ? n : 0;
};

// 적립률 상한(%). 100% 를 넘는 적립은 팔수록 손해라 뜻이 성립하지 않는다.
export const 적립상한퍼센트 = 100;

export const 포인트정책 = (dns) => {
    const s = dns?.setting_obj ?? {};
    return {
        최소주문금액: Math.max(0, 수(s.use_point_min_price)),
        최소보유: Math.max(0, 수(s.point_use_min)),
        최대사용: Math.max(0, 수(s.max_use_point)),
        // 적립률에는 위도 있어야 한다.
        //
        // 「포인트 적립비율」 칸은 % 인데 값이 그냥 숫자다. 1000 을 넣으면 1,000% 로 읽혀
        // **결제금액의 열 배가 포인트로 적립된다.** 「1000원 적립」으로 오해해 치기 쉽다.
        // 서버 사본(utils.js/point-policy.js)과 같은 값이어야 한다.
        적립률: Math.min(적립상한퍼센트, Math.max(0, 수(s.point_rate))),
    };
};

// 이 가맹점이 포인트를 쓰는가.
//
// 최대사용·적립률이 둘 다 0 이면 포인트를 안 쓰는 몰이다 — 고객 화면 어디에도 안 보여야 한다.
// (기본값이 0 이라 아무 설정도 안 한 가맹점은 저절로 여기에 걸린다)
export const 포인트쓰는몰 = (dns) => {
    const p = 포인트정책(dns);
    return p.최대사용 > 0 || p.적립률 > 0;
};

// 이번 주문에서 실제로 쓸 수 있는 최대 포인트와, 못 쓸 때의 이유.
//
// ⚠ '최대사용' 설정값을 그대로 보여주면 안 된다. 보유 500P·설정 10,000P 인 사람에게
//   '10,000P 사용가능'이라고 알려 주고 정작 500P 만 들어가면 그게 더 헷갈린다.
export const 포인트사용상한 = ({ dns, 보유 = 0, 주문금액 = 0 }) => {
    const p = 포인트정책(dns);
    const 잔액 = Math.max(0, 수(보유));
    const 금액 = Math.max(0, 수(주문금액));

    if (p.최대사용 <= 0) return { 상한: 0, 이유: '' };          // 포인트를 안 쓰는 몰
    if (잔액 <= 0) return { 상한: 0, 이유: '사용할 포인트가 없습니다.' };

    // 두 조건을 다 본다(택일이 아니다 — 위 주석 참고). 값이 0 이면 그 조건은 없다.
    if (p.최소보유 > 0 && 잔액 < p.최소보유) {
        return { 상한: 0, 이유: '포인트가 모자랍니다', 기준: p.최소보유, 단위: 'P' };
    }
    if (p.최소주문금액 > 0 && 금액 < p.최소주문금액) {
        return { 상한: 0, 이유: '주문금액이 모자랍니다', 기준: p.최소주문금액, 단위: '원' };
    }
    // 주문금액보다 많이 쓸 수는 없다(결제금액이 음수가 된다).
    return { 상한: Math.floor(Math.min(잔액, p.최대사용, 금액)), 이유: '' };
};

// 이번 주문으로 쌓일 포인트. 소수점은 버린다 — 원장에 소수가 들어가면 합계가 지저분해진다.
export const 적립예정 = ({ dns, 결제금액 = 0 }) => {
    const p = 포인트정책(dns);
    if (p.적립률 <= 0) return 0;
    return Math.floor(Math.max(0, 수(결제금액)) * (p.적립률 / 100));
};
