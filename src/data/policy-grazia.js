// '제3자에게 제공하지 않습니다' 예시 문구는 grazia 에는 사실이 아니다 — 뺀다.
const 지우기 = [
    ['p', '현재 개인정보를 제3자에게 제공하지 않는 경우에는 다음과 같이 표시할 수 있습니다.'],
    ['li', '“회사는 현재 이용자의 개인정보를 제3자에게 제공하고 있지 않습니다.”'],
];

const 같은블록 = (a, b) => a?.[0] === b?.[0] && a?.[1] === b?.[1];

export const graziaPrivacy = (blocks) => {
    let out = (blocks ?? []).filter((b) => !(b?.[0] === 'li' && 빼기.includes(b?.[1])));
    out = out.filter((b) => !지우기.some((x) => 같은블록(b, x)));
    for (const { after, add } of 뒤에넣기) {
        const i = out.findIndex((b) => 같은블록(b, after));
        if (i >= 0) out = [...out.slice(0, i + 1), ...add, ...out.slice(i + 1)];
    }
    return out;
};

export const isGraziaPolicy = (dns) => Number(dns?.id) == 74;
