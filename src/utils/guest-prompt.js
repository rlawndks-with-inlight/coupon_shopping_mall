// 묻지 않았다. 가맹점 요청(2026-08-25)으로 **매번 묻도록** 바꿨다 —
// 회원가입 유도가 목적인데 한 번 넘기면 그 방문 내내 안 뜨는 게 약하다는 것이다.
//
// 그래서 여기에 '그만묻기' 같은 상태를 다시 만들지 말 것. 만들면 요청이 되돌아간다.
// (담기 성공 뒤 window.location.reload() 를 하는 화면이 여럿이라 컴포넌트 상태로는
