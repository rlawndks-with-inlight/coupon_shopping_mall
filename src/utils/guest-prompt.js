// 로그인하지 않은 손님에게 회원가입을 권한다.
//
// 담기·바로구매 버튼은 화면 20여 곳에 흩어져 있지만, 실제로는 길목 세 개로 모인다
//   ① shop-util.js 의 insertCartDataUtil  (장바구니 담기)
//   ② shop-util.js 의 startBuyNow         (바로구매)
//   ③ 주문서 화면 OrderSheet              (장바구니 → 주문하기 로 들어오는 길)
// 그 세 곳에서 이 함수를 부르고, 실제 창은 레이아웃에 한 번만 걸린 GuestSignupPrompt 가 띄운다.
// 그래서 프레임이 늘어도 여기만 지키면 된다.
//
// ③ 을 왜 '주문서'에 걸었나 — '주문하기' 버튼은 카트 화면 10개(shop 데모 9 + blog 공용)에
// 흩어져 있다. 열 군데를 각각 고치면 프레임이 늘 때 또 빠진다. 바로구매도 장바구니도
// 결국 주문서 한 곳으로 오므로, 도착지에 한 번 거는 편이 안 샌다.
//
// ⚠ 막는 장치가 아니다.
//   예전에 비회원을 로그인 화면으로 튕기는 코드가 있었는데, 그러면 비회원 구매 자체가
//   불가능해져서 걷어낸 이력이 있다(헤더 주석에 남아 있다).
//   그래서 창에는 반드시 「비회원으로 계속」이 있어야 한다.

// 창을 여는 함수. GuestSignupPrompt 가 마운트되면서 꽂아 넣는다.
let 열기 = null;

export const setGuestPromptOpener = (fn) => { 열기 = fn; };

/**
 * @returns {Promise<boolean>} true = 하던 일을 계속한다 / false = 멈춘다(회원가입·로그인으로 떠났다)
 *
 * 창이 아직 안 걸렸으면(레이아웃 밖에서 부른 경우) 그냥 진행시킨다.
 * 여기서 막으면 창이 없는 화면에서는 담기가 통째로 죽는다.
 */
export const askGuestSignup = () => (열기 ? 열기() : Promise.resolve(true));

