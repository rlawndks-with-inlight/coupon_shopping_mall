// 사진 위에 얹히는 아이콘 버튼의 배경.
//
// [증상] 상품 상세 맨 위에서 뒤로가기가 안 보인다는 얘기가 있었다.
// [원인] 그 자리에서 헤더는 투명해지고 아이콘은 흰색이 된다(사진 위에 얹으려고 그렇게 짰다).
//        그런데 상품 사진은 대개 흰 배경에서 찍는다 — 흰 화살표가 흰 배경에 그대로 묻힌다.
//        어두운 사진에서는 잘 보이니 '가끔 안 보인다' 로 나타나서 원인을 짚기 어렵다.
// [처리] 사진 위에 있을 때만 아이콘 뒤에 반투명 원을 깔아 밝든 어둡든 읽히게 한다.
//        (네이버·쿠팡 상품상세도 같은 방식이다)
//
// 색을 고정하지 않는 원칙과 어긋나 보이지만 여기는 다르다 — 배경이 '프레임의 색'이 아니라
// '가맹점이 올린 사진'이라 무슨 색일지 알 수 없다. 그래서 대비를 스스로 만들어야 한다.
export const 사진위아이콘 = (사진위인가) => (사진위인가 ? {
    background: 'rgba(0,0,0,0.38)',
    '&:hover': { background: 'rgba(0,0,0,0.52)' },
} : {});
