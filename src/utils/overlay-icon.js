// 사진 위에 얹히는 헤더의 배경.
//
// [증상] 상품 상세 맨 위에서 뒤로가기가 안 보인다는 얘기가 있었다.
// [원인] 그 자리에서 헤더는 투명해지고 아이콘은 흰색이 된다(사진 위에 얹으려고 그렇게 짰다).
//        그런데 상품 사진은 대개 흰 배경에서 찍는다 — 흰 아이콘이 흰 배경에 그대로 묻힌다.
//        어두운 사진에서는 잘 보이니 '가끔 안 보인다' 로 나타나 원인을 짚기 어려웠다.
// [처리] 사진 위쪽에 어두운 그라데이션을 한 겹 깐다(쿠팡·네이버 상품상세와 같은 방식).
//        아이콘마다 동그라미를 깔면 뒤로가기·검색·장바구니가 줄지어 무거워 보인다.
//        그라데이션은 아이콘을 건드리지 않고 그 줄 전체를 읽히게 하며, 사진도 거의 가리지 않는다.
//
// 색을 고정하지 않는 원칙과 어긋나 보이지만 여기는 다르다 — 배경이 '프레임의 색'이 아니라
// '가맹점이 올린 사진'이라 무슨 색일지 알 수 없다. 그래서 대비를 스스로 만들어야 한다.
export const 사진위그라데이션 = 'linear-gradient(to bottom, rgba(0,0,0,0.45), rgba(0,0,0,0))';

// 헤더 배경값을 고른다. 사진 위면 그라데이션, 아니면 원래 색.
export const 헤더배경 = (사진위인가, 원래색) => (사진위인가 ? 사진위그라데이션 : 원래색);
